CREATE INDEX IF NOT EXISTS ix_proposals_req ON proposals (client_request_id);
CREATE INDEX IF NOT EXISTS ix_proposals_status ON proposals (organization_id, status);
ALTER TABLE contracts ADD COLUMN IF NOT EXISTS accepted_version_id UUID REFERENCES proposal_versions(id) ON DELETE RESTRICT;
